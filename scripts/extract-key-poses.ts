// Extracts each Exercise's Key poses from its vendored ExerciseDB GIF:
//
//   npm run extract-key-poses   (copy-exercisedb also runs it)
//
// A Key pose is a frame the GIF holds for at least HOLD_MS; the frames between
// them are only a dissolve, which Follow-along redraws as a CSS cross-fade.
// Writes public/exercisedb/poses/<id>-<n>.webp, a README with the AGPL §5
// modification notice, and src/library/key-poses.json: { id: [hold in ms, ...] }.

import { mkdir, readdir, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const HOLD_MS = 500

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const gifDir = path.join(root, 'public/exercisedb')
const poseDir = path.join(gifDir, 'poses')
const holdsFile = path.join(root, 'src/library/key-poses.json')

const readme = `# Key poses (modified from ExerciseDB v1)

Still frames of each Exercise, served as \`<id>-<n>.webp\`. Follow-along cross-fades between them.

- **Modified work:** each file is a frame of the GIF of the same id in [\`..\`](..), the ExerciseDB v1 subset. The frames are the ones the GIF holds for at least ${HOLD_MS} ms, re-encoded as WebP. Modified on 2026-11-17 and on every rerun since.
- **Licence:** AGPL-3.0, like the GIFs they come from; see [\`../README.md\`](../README.md) and this repo's [LICENSE](../../../LICENSE).
- **Source:** the GIFs in \`..\` plus \`scripts/extract-key-poses.ts\`.

Generated by \`scripts/extract-key-poses.ts\`; rerun it instead of editing these files.
`

/** The page numbers and holds of a GIF's Key poses; its first frame if it holds none. */
export function keyPoses(delays: readonly number[]): { page: number; holdMs: number }[] {
  const poses = delays.flatMap((holdMs, page) => (holdMs >= HOLD_MS ? [{ page, holdMs }] : []))
  return poses.length > 0 ? poses : [{ page: 0, holdMs: delays[0] ?? 0 }]
}

export async function extractKeyPoses() {
  const ids = (await readdir(gifDir))
    .filter((file) => file.endsWith('.gif'))
    .map((file) => file.slice(0, -'.gif'.length))
    .sort()

  await rm(poseDir, { recursive: true, force: true })
  await mkdir(poseDir, { recursive: true })

  const holds: Record<string, number[]> = {}
  for (const id of ids) {
    const gif = path.join(gifDir, `${id}.gif`)
    const { delay = [] } = await sharp(gif).metadata()
    const poses = keyPoses(delay)
    for (const [n, { page }] of poses.entries()) {
      await sharp(gif, { page })
        .webp({ quality: 85, effort: 6 })
        .toFile(path.join(poseDir, `${id}-${n}.webp`))
    }
    holds[id] = poses.map((pose) => pose.holdMs)
  }

  await writeFile(path.join(poseDir, 'README.md'), readme)
  await writeFile(holdsFile, JSON.stringify(holds, null, 2) + '\n')
  console.log(`Extracted Key poses for ${ids.length} Exercises`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await extractKeyPoses()
