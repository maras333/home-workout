// One-off script: copies the curated subset of ExerciseDB v1 into this repo,
// unmodified, from the pinned snapshot of bootstrapping-lab/exercisedb-api.
//
//   npm run copy-exercisedb
//
// The id list is the set of keys in src/library/curation.ts. Rerunning after
// changing that list rewrites the records file, downloads GIFs for new ids and
// deletes GIFs for ids no longer listed. It then extracts each GIF's Key poses
// (scripts/extract-key-poses.ts), the one modified copy, kept apart in poses/.

import { existsSync } from 'node:fs'
import { mkdir, readdir, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { curation } from '../src/library/curation.ts'
import { extractKeyPoses } from './extract-key-poses.ts'

const REPO = 'bootstrapping-lab/exercisedb-api'
const COMMIT = '7cdc82e1a14b06799d16c819d1082f3debb425ce'
const SHORT_COMMIT = COMMIT.slice(0, 7)
const RAW_BASE = `https://raw.githubusercontent.com/${REPO}/${COMMIT}`

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const recordsDir = path.join(root, 'src/library/exercisedb')
const gifDir = path.join(root, 'public/exercisedb')

type ExerciseRecord = { exerciseId: string } & Record<string, unknown>

const readme = (contents: string, licencePath: string) => `# ExerciseDB v1 subset

${contents}

- **Source:** [${REPO}](https://github.com/${REPO}) at commit [\`${SHORT_COMMIT}\`](https://github.com/${REPO}/tree/${COMMIT})
- **Unmodified subset:** the files here are copied byte-for-byte (GIFs) or record-for-record (\`exercises.json\`) from that commit. Only a subset of Exercises is included; nothing is edited. Our own tags live separately in \`src/library/curation.ts\`.
- **Licence:** AGPL-3.0, see the [source repo's LICENSE](https://github.com/${REPO}/blob/${COMMIT}/LICENSE) and this repo's [LICENSE](${licencePath}).

Generated by \`scripts/copy-exercisedb.ts\`; rerun it instead of editing these files.
`

async function fetchOk(url: string): Promise<Response> {
  const response = await fetch(url)
  if (!response.ok) throw new Error(`GET ${url} failed: ${response.status} ${response.statusText}`)
  return response
}

async function main() {
  const ids = new Set(Object.keys(curation))
  console.log(`Copying ${ids.size} Exercises from ${REPO}@${SHORT_COMMIT}`)

  const allRecords = (await (
    await fetchOk(`${RAW_BASE}/src/data/exercises.json`)
  ).json()) as ExerciseRecord[]
  const records = allRecords.filter((record) => ids.has(record.exerciseId))
  const missing = [...ids].filter((id) => !records.some((record) => record.exerciseId === id))
  if (missing.length > 0) throw new Error(`Not in the dataset: ${missing.join(', ')}`)

  await mkdir(recordsDir, { recursive: true })
  await writeFile(path.join(recordsDir, 'exercises.json'), JSON.stringify(records, null, 2) + '\n')
  await writeFile(
    path.join(recordsDir, 'README.md'),
    readme('Exercise records (`exercises.json`) bundled into the app.', '../../../LICENSE'),
  )

  await mkdir(gifDir, { recursive: true })
  for (const file of await readdir(gifDir)) {
    if (file.endsWith('.gif') && !ids.has(file.slice(0, -'.gif'.length))) {
      await rm(path.join(gifDir, file))
      console.log(`Removed ${file}`)
    }
  }
  for (const id of ids) {
    const target = path.join(gifDir, `${id}.gif`)
    if (existsSync(target)) continue
    const gif = await fetchOk(`${RAW_BASE}/media/${id}.gif`)
    await writeFile(target, new Uint8Array(await gif.arrayBuffer()))
    console.log(`Downloaded ${id}.gif`)
  }
  await writeFile(
    path.join(gifDir, 'README.md'),
    readme(
      'Exercise GIFs, served as static files named by Exercise id. [`poses/`](poses) holds still frames modified from them; it has its own README.',
      '../../LICENSE',
    ),
  )
  await extractKeyPoses()

  console.log('Done')
}

await main()
